import random
from datetime import datetime, timedelta
from fastapi import APIRouter, Depends
from sqlalchemy.orm import Session
from backend.database import get_db
from backend.models import User, Subscription, Invoice, InvoiceLineItem
from backend.schemas import BillingCycleResult
from backend.security import require_staff_or_admin

router = APIRouter(prefix="/api/billing", tags=["Billing Engine"])

@router.post("/run-cycle", response_model=BillingCycleResult)
def run_billing_cycle(
    current_user: User = Depends(require_staff_or_admin),
    db: Session = Depends(get_db)
):
    """
    Automated Invoice Generation Engine & Dunning Engine:
    1. Scans all Active subscriptions.
    2. Generates cycle invoices for subscriptions.
    3. Advances next_billing_date.
    4. Identifies past-due posted invoices and flags them as 'overdue'.
    """
    now = datetime.utcnow()
    cycle_run_id = f"CYCLE-{now.strftime('%Y%m%d%H%M%S')}-{random.randint(100, 999)}"

    # 1. Check past due invoices to mark as overdue
    past_due_invoices = db.query(Invoice).filter(
        Invoice.status == "posted",
        Invoice.due_date < now
    ).all()

    overdue_count = 0
    for inv in past_due_invoices:
        inv.status = "overdue"
        inv.notes = (inv.notes or "") + f" [Flagged overdue during cycle {cycle_run_id}]"
        overdue_count += 1

    # 2. Find active subscriptions to process
    active_subs = db.query(Subscription).filter(Subscription.status == "active").all()

    invoices_generated = 0
    total_billed = 0.0
    subs_advanced = 0
    details = []

    for sub in active_subs:
        # Determine interval delta
        interval_days = 30
        if sub.billing_interval == "quarterly":
            interval_days = 90
        elif sub.billing_interval == "annually":
            interval_days = 365

        # Create new cycle invoice
        inv_num = f"INV-{now.year}-{random.randint(10000, 99999)}"
        new_inv = Invoice(
            invoice_number=inv_num,
            subscription_id=sub.id,
            customer_id=sub.customer_id,
            issue_date=now,
            due_date=now + timedelta(days=14),
            status="posted",
            subtotal=sub.subtotal,
            discount_amount=sub.discount_amount,
            tax_amount=sub.tax_amount,
            total_amount=sub.total_amount,
            amount_paid=0.0,
            billing_cycle_run_id=cycle_run_id,
            notes=f"Generated by automated billing cycle engine for {sub.subscription_code}",
            created_at=now
        )
        db.add(new_inv)
        db.flush()

        line_item = InvoiceLineItem(
            invoice_id=new_inv.id,
            description=f"{sub.plan.name} - Recurring {sub.billing_interval.capitalize()} Cycle",
            quantity=sub.quantity,
            unit_price=sub.unit_price,
            total_price=sub.subtotal
        )
        db.add(line_item)

        # Advance next billing date
        sub.next_billing_date = now + timedelta(days=interval_days)
        sub.updated_at = now

        invoices_generated += 1
        total_billed += sub.total_amount
        subs_advanced += 1
        details.append(f"Generated {inv_num} for {sub.subscription_code} (${sub.total_amount:,.2f})")

    db.commit()

    return {
        "invoices_generated": invoices_generated,
        "total_amount_billed": round(total_billed, 2),
        "subscriptions_advanced": subs_advanced,
        "overdue_marked": overdue_count,
        "run_timestamp": now,
        "details": details
    }
